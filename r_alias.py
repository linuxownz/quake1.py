def GLAlias_CreateShaders():
    bindings : list[glquake.glsl_attrib_binding_t] = []

    bindings.append( glquake.glsl_attrib_binding_t('TexCoords', texCoordsAttrIndex))
    bindings.append( glquake.glsl_attrib_binding_t('Pose1Vert', pose1VertexAttrIndex))
    bindings.append( glquake.glsl_attrib_binding_t('Pose1Normal', pose1NormalAttrIndex))
    bindings.append( glquake.glsl_attrib_binding_t('Pose2Vert', pose2VertexAttrIndex))
    bindings.append( glquake.glsl_attrib_binding_t('Pose2Normal', pose2NormalAttrIndex))

    vertSource = '''#version 110
    uniform float Blend;
    uniform vec3 ShadeVector;
    uniform vec4 LightColor;
    attribute vec4 TexCoords; // only xy are used
    attribute vec4 Pose1Vert;
    attribute vec3 Pose1Normal;
    attribute vec4 Pose2Vert;
    attribute vec3 Pose2Normal;

    varying float FogFragCoord;

    float r_avertexnormal_dot(vec3 vertexnormal) // from MH
    {
            float dot = dot(vertexnormal, ShadeVector);
            // wtf - this reproduces anorm_dots within as reasonable a degree of tolerance as the >= 0 case
            if (dot < 0.0)
                return 1.0 + dot * (13.0 / 44.0);
            else
                return 1.0 + dot;
    }
    void main()
    {
       gl_TexCoord[0] = TexCoords;
       vec4 lerpedVert = mix(vec4(Pose1Vert.xyz, 1.0), vec4(Pose2Vert.xyz, 1.0), Blend);
       gl_Position = gl_ModelViewProjectionMatrix * lerpedVert;
       FogFragCoord = gl_Position.w;
       float dot1 = r_avertexnormal_dot(Pose1Normal);
       float dot2 = r_avertexnormal_dot(Pose2Normal);
       gl_FrontColor = LightColor * vec4(vec3(mix(dot1, dot2, Blend)), 1.0);
    };'''

    fragSource = '''#version 110
    uniform sampler2D Tex;
    uniform sampler2D FullbrightTex;
    uniform bool UseFullbrightTex;
    uniform bool UseOverbright;
    uniform bool UseAlphaTest;

    varying float FogFragCoord;

    void main()
    {
       vec4 result = texture2D(Tex, gl_TexCoord[0].xy);
       if (UseAlphaTest && (result.a < 0.666))
           discard;
       result *= gl_Color;
       if (UseOverbright)
           result.rgb *= 2.0;
       if (UseFullbrightTex)
           result += texture2D(FullbrightTex, gl_TexCoord[0].xy);
       result = clamp(result, 0.0, 1.0);
       float fog = exp(-gl_Fog.density * gl_Fog.density * FogFragCoord * FogFragCoord);
       fog = clamp(fog, 0.0, 1.0);
       result = mix(gl_Fog.color, result, fog);
       result.a = gl_Color.a; // FIXME: This will make almost transparent things cut holes though heavy fog
       gl_FragColor = result;
    };'''

    if not gl_vidsdl.gl_glsl_alias_able:
        return

    global r_alias_program
    r_alias_program = gl_rmisc.GL_CreateProgram(vertSource, fragSource, len(bindings), bindings)

    if r_alias_program != 0:
        global blendLoc, shadervectorLoc, lightColorLoc
        global texLoc, fullbrightTexLoc, useFullbrightTexLoc
        global useOverbrightLoc, useAlphaTestLoc

        blendLoc            = gl_rmisc.GL_GetUniformLocation(r_alias_program, 'Blend')
        shadervectorLoc     = gl_rmisc.GL_GetUniformLocation(r_alias_program, 'ShadeVector')
        lightColorLoc       = gl_rmisc.GL_GetUniformLocation(r_alias_program, 'LightColor')
        texLoc              = gl_rmisc.GL_GetUniformLocation(r_alias_program, 'Tex')
        fullbrightTexLoc    = gl_rmisc.GL_GetUniformLocation(r_alias_program, 'FullbrightTex')
        useFullbrightTexLoc = gl_rmisc.GL_GetUniformLocation(r_alias_program, 'UseFullbrightTex')
        useOverbrightLoc    = gl_rmisc.GL_GetUniformLocation(r_alias_program, 'UseOverbright')
        useAlphaTestLoc     = gl_rmisc.GL_GetUniformLocation(r_alias_program, 'UseAlphaTest')


def _alias_decoded_commands(paliashdr: quakedef.aliashdr_t) -> list:
    """gl_mesh stores commands as ints: count, then (s, t) float bit patterns.
    Decode once into [count, s, t, s, t, ..., 0] and cache on the header."""
    dec = getattr(paliashdr, "_commands_decoded", None)
    if dec is not None:
        return dec

    raw = paliashdr.commands
    dec = []
    k = 0
    while k < len(raw):
        count = raw[k]
        k += 1
        dec.append(count)
        if count == 0:
            break
        n = -count if count < 0 else count
        for _ in range(n):
            s_f = struct.unpack("<f", struct.pack("<i", raw[k]))[0]
            t_f = struct.unpack("<f", struct.pack("<i", raw[k + 1]))[0]
            dec.append(s_f)
            dec.append(t_f)
            k += 2

    paliashdr._commands_decoded = dec
    return dec


