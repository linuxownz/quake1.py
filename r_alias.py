SHADOW_SKEW_X = -0.7
SHADOW_SKEW_Y = 0
SHADOW_VSCALE = 0
SHADOW_HEIGHT = 0.1

def GL_DrawAliasShadow(e: render.entity_t):
    global entalpha, shading
    shadowmatrix: list[float] = [
        1,              0,              0,              0,
        0,              1,              0,              0,
        SHADOW_SKEW_X,  SHADOW_SKEW_Y,  SHADOW_VSCALE,  0,
        0,              0,              SHADOW_HEIGHT,  1
    ]


    if gl_rmain.R_CullModelForEntity(e):
        return

    if e == cl_main.cl.viewent or e.model.flags & quakedef.MOD_NOSHADOW:
        return

    entalpha = protocol.ENTALPHA_DECODE(e.alpha)
    if entalpha == 0:
        return

    lerpdata: lerpdata_t = None
    paliashdr: quakedef.aliashdr_t = gl_model.Mod_Extradata(e.model)
    R_SetupAliasFrame(paliashdr, e.frame, lerpdata)
    R_SetupEntityTransform(e, lerpdata)
    gl_rlight.R_LightPoint(e.origin)
    lheight = gl_rmain.currententity.origin[2] - gl_rlight.lightspot[2]

    gl.glPushMatrix ();
    gl.glTranslatef (lerpdata.origin[0],  lerpdata.origin[1],  lerpdata.origin[2]);
    gl.glTranslatef (0,0,-lheight);
    gl.glMultMatrixf (shadowmatrix);
    gl.glTranslatef (0,0,lheight);
    gl.glRotatef (lerpdata.angles[1],  0, 0, 1);
    gl.glRotatef (-lerpdata.angles[0],  0, 1, 0);
    gl.glRotatef (lerpdata.angles[2],  1, 0, 0);
    gl.glTranslatef (paliashdr.scale_origin[0], paliashdr.scale_origin[1], paliashdr.scale_origin[2])
    gl.glScalef (paliashdr.scale[0], paliashdr.scale[1], paliashdr.scale[2]);

    gl.glDepthMask(gl.GL_FALSE);
    gl.glEnable (gl.GL_BLEND);
    gl_texmgr.GL_DisableMultitexture ();
    gl.glDisable (gl.GL_TEXTURE_2D);
    shading = False;
    gl.glColor4f(0,0,0,entalpha * 0.5);
    GL_DrawAliasFrame (paliashdr, lerpdata);
    gl.glEnable (gl.GL_TEXTURE_2D);
    gl.glDisable (gl.GL_BLEND);
    gl.glDepthMask(gl.GL_TRUE);

    gl.glPopMatrix ();


