            gl.glTexEnvi(gl.GL_TEXTURE_ENV, gl.GL_SOURCE0_RGB_EXT, gl.GL_TEXTURE)
            gl.glTexEnvi(gl.GL_TEXTURE_ENV, gl.GL_SOURCE1_RGB_EXT, gl.GL_PRIMARY_COLOR_EXT)
            gl.glTexEnvf(gl.GL_TEXTURE_ENV, gl.GL_RGB_SCALE_EXT, 2.0)
            GL_DrawAliasFrame (paliashdr, lerpdata)
            gl.glTexEnvf(gl.GL_TEXTURE_ENV, gl.GL_RGB_SCALE_EXT, 1.0)
            gl.glTexEnvf(gl.GL_TEXTURE_ENV, gl.GL_TEXTURE_ENV_MODE, gl.GL_REPLACE)

            if fb:
                gl.glTexEnvf(gl.GL_TEXTURE_ENV, gl.GL_TEXTURE_ENV_MODE, gl.GL_MODULATE)
                gl_texmgr.GL_Bind(fb);
                gl.glEnable(gl.GL_BLEND);
                gl.glBlendFunc (gl.GL_ONE, gl.GL_ONE);
                gl.glDepthMask(gl.GL_FALSE);
                shading = False;
                gl.glColor3f(entalpha,entalpha,entalpha);
                gl_fog.Fog_StartAdditive ();
